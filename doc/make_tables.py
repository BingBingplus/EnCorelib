#!/usr/bin/env python3
"""Turn the runs of doc/compare_options.sh into the tables of section 6.

    python3 doc/make_tables.py

reads   doc/out/options/<tag>.out
writes  doc/out/table_eps.tex, table_stepB.tex, table_method.tex,
        table_order.tex, table_mode.tex, table_combo.tex (LaTeX tabulars)
        doc/out/options_summary.txt                       (the same, as text)
"""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OPT = os.path.join(HERE, "out", "options")
OUT = os.path.join(HERE, "out")

PROBLEMS = [("eg1", "Eg1 Lotka-Volterra", "5.5"), ("eg2", "Eg2 Van der Pol", "2"),
            ("eg3", "Eg3 quadratic", "4"), ("eg4", "Eg4 FitzHugh-Nagumo", "4"),
            ("eg5", "Eg5 Lorenz", "4"), ("eg6", "Eg6 R\\\"ossler", "4")]
SUMMARY = []


def read(tag):
    """(seconds, #C, wmax(B1)) of one run, or None if it printed no result."""
    path = os.path.join(OPT, tag + ".out")
    if not os.path.exists(path):
        return None
    text = open(path).read()
    t = re.search(r"^time\(ms\)=(\d+)", text, re.M)
    w = re.search(r"^wmax\(B1\)=([0-9.eE+-]+)", text, re.M)
    c = re.search(r"^#\(C\)=(\d+)", text, re.M)
    if not (t and w and c):
        return None
    r = (int(t.group(1)) / 1000.0, int(c.group(1)), float(w.group(1)))
    SUMMARY.append("%-24s %9.2f s  #C=%-6d wmax(B1)=%.6f" % (tag, r[0], r[1], r[2]))
    return r


def sec(r):
    if r is None:
        return "--"
    return ("%.1f" % r[0]) if r[0] < 10 else ("%.0f" % r[0])


def cnt(r):
    return "--" if r is None else "%d" % r[1]


def wid(r):
    return "--" if r is None else "%.3f" % r[2]


def write(name, head, rows, cols):
    lines = ["%% generated by doc/make_tables.py from doc/out/options/",
             "\\begin{tabular}{%s}" % cols, "\\toprule"] + head + ["\\midrule"]
    lines += rows + ["\\bottomrule", "\\end{tabular}"]
    with open(os.path.join(OUT, name), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote doc/out/" + name)


def default(e, eps):
    return read("eps_%s_e1.0_s0" % e) if eps == "1.0" else read("stepB_%s_e%s_s0" % (e, eps))


def table_eps():
    rows = []
    for e, name, H in PROBLEMS:
        r = [default(e, eps) for eps in ("1.0", "0.5", "0.1")]
        rows.append("%s & %s & %s \\\\" % (name, H, " & ".join(
            "%s & %s" % (sec(x), cnt(x)) for x in r)))
    head = ["& & \\multicolumn{2}{c}{$\\varepsilon=1$} & \\multicolumn{2}{c}{$\\varepsilon=0.5$}"
            " & \\multicolumn{2}{c}{$\\varepsilon=0.1$} \\\\",
            "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}",
            "problem & $H$ & s & $\\#(C)$ & s & $\\#(C)$ & s & $\\#(C)$ \\\\"]
    write("table_eps.tex", head, rows, "llrrrrrr")


def table_stepB():
    rows = []
    for eps in ("0.5", "0.1"):
        for e, name, H in PROBLEMS:
            r = [read("stepB_%s_e%s_s%d" % (e, eps, s)) for s in range(4)]
            rows.append("%s & %s & %s & %s & %s \\\\" % (
                name, H, eps, " & ".join(sec(x) for x in r), " & ".join(wid(x) for x in r)))
        rows.append("\\addlinespace")
    r = [read("lorenzT5_s%d" % s) for s in range(4)]
    rows.append("Eg5 Lorenz & 5 & 1 & %s & %s \\\\" % (
        " & ".join(sec(x) for x in r), " & ".join(wid(x) for x in r)))
    head = ["& & & \\multicolumn{4}{c}{time (s) for \\texttt{stepB}} "
            "& \\multicolumn{4}{c}{$w_{\\max}(B_1)$ for \\texttt{stepB}} \\\\",
            "\\cmidrule(lr){4-7}\\cmidrule(lr){8-11}",
            "problem & $H$ & $\\varepsilon$ & 0 & 1 & 2 & 3 & 0 & 1 & 2 & 3 \\\\"]
    write("table_stepB.tex", head, rows, "lll rrrr rrrr")


def table_method():
    rows = []
    for eps in ("0.5", "0.1"):
        for e, name, H in PROBLEMS:
            r = [default(e, eps)] + [read("method_%s_e%s_m%d" % (e, eps, m)) for m in (1, 2)]
            rows.append("%s & %s & %s & %s & %s \\\\" % (
                name, H, eps, " & ".join(sec(x) for x in r), " & ".join(wid(x) for x in r)))
        rows.append("\\addlinespace")
    rows.pop()
    head = ["& & & \\multicolumn{3}{c}{time (s) for \\texttt{method}} "
            "& \\multicolumn{3}{c}{$w_{\\max}(B_1)$ for \\texttt{method}} \\\\",
            "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
            "problem & $H$ & $\\varepsilon$ & 0 & 1 & 2 & 0 & 1 & 2 \\\\"]
    write("table_method.tex", head, rows, "lll rrr rrr")


def table_order():
    rows = []
    for e, eps in (("eg1", "0.1"), ("eg5", "0.5"), ("eg6", "0.1")):
        name, H = [(n, h) for (k, n, h) in PROBLEMS if k == e][0]
        r = [read("order_%s_e%s_o%d" % (e, eps, o)) if o != 20 else default(e, eps)
             for o in (10, 15, 20, 30)]
        rows.append("%s & %s & %s & %s & %s \\\\" % (
            name, H, eps, " & ".join(sec(x) for x in r), " & ".join(wid(x) for x in r)))
    head = ["& & & \\multicolumn{4}{c}{time (s) for \\texttt{order}} "
            "& \\multicolumn{4}{c}{$w_{\\max}(B_1)$ for \\texttt{order}} \\\\",
            "\\cmidrule(lr){4-7}\\cmidrule(lr){8-11}",
            "problem & $H$ & $\\varepsilon$ & 10 & 15 & 20 & 30 & 10 & 15 & 20 & 30 \\\\"]
    write("table_order.tex", head, rows, "lll rrrr rrrr")


def table_mode():
    rows = []
    for e, name, H in PROBLEMS:
        a, b = default(e, "0.1"), read("mode1_%s_e0.1" % e)
        rows.append("%s & %s & %s & %s & %s & %s & %s & %s \\\\" % (
            name, H, sec(a), cnt(a), wid(a), sec(b), cnt(b), wid(b)))
    head = ["& & \\multicolumn{3}{c}{\\texttt{mode=0} (EndCover)} "
            "& \\multicolumn{3}{c}{\\texttt{mode=1} (Boundary)} \\\\",
            "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
            "problem & $H$ & s & $\\#(C)$ & $w_{\\max}(B_1)$ & s & $\\#(C)$ & $w_{\\max}(B_1)$ \\\\"]
    write("table_mode.tex", head, rows, "ll rrr rrr")




def table_combo():
    rows = []
    for e, name, H in PROBLEMS:
        a, b = read("combo0_%s_e0.1" % e), read("combo_%s_e0.1" % e)
        rows.append("%s & %s & 0.1 & %s & %s & %s & %s & %s & %s \\\\" % (
            name, H, sec(a), cnt(a), wid(a), sec(b), cnt(b), wid(b)))
    a, b = read("combo0_lorenzT5"), read("combo_lorenzT5")
    rows.append("Eg5 Lorenz & 5 & 1 & %s & %s & %s & %s & %s & %s \\\\" % (
        sec(a), cnt(a), wid(a), sec(b), cnt(b), wid(b)))
    head = ["& & & \\multicolumn{3}{c}{the example files} "
            "& \\multicolumn{3}{c}{\\texttt{method=2 stepB=3}} \\\\",
            "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}",
            "problem & $H$ & $\\varepsilon$ & s & $\\#(C)$ & $w_{\\max}(B_1)$ "
            "& s & $\\#(C)$ & $w_{\\max}(B_1)$ \\\\"]
    write("table_combo.tex", head, rows, "lll rrr rrr")


def main():
    for f in (table_eps, table_stepB, table_method, table_order, table_mode, table_combo):
        f()
    with open(os.path.join(OUT, "options_summary.txt"), "w") as fh:
        fh.write("\n".join(sorted(set(SUMMARY))) + "\n")
    print("wrote doc/out/options_summary.txt")


if __name__ == "__main__":
    main()
